let failed = 0
const check = (ok, msg) => { if (!ok) { console.log('  ✗ ' + msg); failed++ } }

for (const [file, body] of Object.entries(bodies)) {
  const p = path.join(root, file)
  let text = fs.readFileSync(p, 'utf8')

  if (CHECK) {
    check(text.includes(H_PITFALLS), `${file}: 缺少 ${H_PITFALLS}`)
    check(text.includes(H_SHARING), `${file}: 缺少 ${H_SHARING}`)
    check(text.includes(H_TRADEOFF), `${file}: 缺少 ${H_TRADEOFF}`)
    check(text.includes(SAMPLE), `${file}: 缺少示例短码`)
    continue
  }

  if (text.includes(H_PITFALLS)) { console.log('  = ' + file + ' 已有该章节，跳过'); continue }

  const anchor = text.indexOf('## License')
  if (anchor === -1) { console.log('  ✗ ' + file + ' 找不到 ## License 锚点'); failed++; continue }
  text = text.slice(0, anchor) + '\n' + body + '\n' + text.slice(anchor)
  fs.writeFileSync(p, text)
  console.log('  ✓ ' + file)
}

if (CHECK) {
  // 五语 `## ` 标题必须逐字一致（含新增三个）
  const sets = {}
  for (const f of ['README.md', 'README-zh.md', 'README-es.md', 'README-pt.md', 'README-hi.md']) {
    sets[f] = fs.readFileSync(path.join(root, f), 'utf8')
      .split('\n').filter((l) => l.startsWith('## ')).sort().join('\n')
  }
  const base = sets['README.md']
  for (const [f, s] of Object.entries(sets)) check(s === base, `${f} 的 ## 标题与 README.md 不一致`)

  console.log(failed === 0 ? '\n检查通过' : `\n${failed} 项失败`)
  process.exit(failed === 0 ? 0 : 1)
}
